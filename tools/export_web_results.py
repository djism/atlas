"""Export recorded KITTI results for the website's "Real data" section.

Reads the ground truth and the pose files written by `atlas_kitti odometry`
and `tools/kiss_icp_baseline.py`, and writes web/src/data/kittiPaths.ts:
top-down paths (every `step`-th pose) and per-stretch step errors. Standard
library only, so it runs with any Python 3.8+:

    python3 -I tools/export_web_results.py <odometry_dir> results web/src/data/kittiPaths.ts

<odometry_dir> is .../odometry/dataset (poses/, sequences/). Expected in
results/: atlas_<seq>_map.txt, atlas_<seq>_scan_deskew.txt, kiss_<seq>.txt for
sequences 04 and 07. All estimates are in the Velodyne frame of scan 0; the
truth is converted to it with Tr: velodyne_i = Tr^-1 * camera_i * Tr.

Plot axes match the bird's-eye images and `atlas_kitti plot`: u = -y (right
on screen), v = x (up on screen), meters. Table numbers (drift, time, memory)
are not computed here; they come from `atlas_kitti score` and the streaming
runs recorded in docs/kitti.md.
"""
import json
import math
import sys

SEQUENCES = {"07": 100, "04": 30}  # sequence -> scans per error stretch
STEP = 3  # keep every 3rd pose for the drawn path


def read_poses(path):
    poses = []
    with open(path) as f:
        for line in f:
            v = [float(x) for x in line.split()]
            if len(v) != 12:
                raise ValueError(f"{path}: expected 12 numbers per line")
            poses.append([v[0:4], v[4:8], v[8:12], [0.0, 0.0, 0.0, 1.0]])
    return poses


def read_tr(calib_path):
    with open(calib_path) as f:
        for line in f:
            if line.startswith("Tr:"):
                v = [float(x) for x in line[3:].split()]
                return [v[0:4], v[4:8], v[8:12], [0.0, 0.0, 0.0, 1.0]]
    raise ValueError(f"{calib_path}: no Tr line")


def mul(a, b):
    return [[sum(a[i][k] * b[k][j] for k in range(4)) for j in range(4)] for i in range(4)]


def inv(m):
    """Inverse of a rigid transform: [R^T | -R^T t]."""
    r = [[m[j][i] for j in range(3)] for i in range(3)]
    t = [-sum(r[i][k] * m[k][3] for k in range(3)) for i in range(3)]
    return [r[0] + [t[0]], r[1] + [t[1]], r[2] + [t[2]], [0.0, 0.0, 0.0, 1.0]]


def path(poses):
    idx = list(range(0, len(poses), STEP))
    if idx[-1] != len(poses) - 1:
        idx.append(len(poses) - 1)
    return [[round(-poses[i][1][3], 2), round(poses[i][0][3], 2)] for i in idx]


def stretch_errors(truth, estimate, per):
    """Mean distance between estimated and true step, cm, per stretch of scans."""
    errors = []
    for i in range(len(estimate) - 1):
        true_step = mul(inv(truth[i]), truth[i + 1])
        est_step = mul(inv(estimate[i]), estimate[i + 1])
        e = mul(inv(true_step), est_step)
        errors.append(math.sqrt(e[0][3] ** 2 + e[1][3] ** 2 + e[2][3] ** 2))
    return [round(100 * sum(errors[i:i + per]) / len(errors[i:i + per]), 2) for i in range(0, len(errors), per)]


def main():
    odometry, results, out = sys.argv[1], sys.argv[2], sys.argv[3]
    data = {}
    for seq, per in SEQUENCES.items():
        tr = read_tr(f"{odometry}/sequences/{seq}/calib.txt")
        truth = [mul(mul(inv(tr), c), tr) for c in read_poses(f"{odometry}/poses/{seq}.txt")]
        runs = {
            "atlas": read_poses(f"{results}/atlas_{seq}_map.txt"),
            "kiss": read_poses(f"{results}/kiss_{seq}.txt"),
            "noMap": read_poses(f"{results}/atlas_{seq}_scan_deskew.txt"),
        }
        for name, poses in runs.items():
            if len(poses) != len(truth):
                raise ValueError(f"sequence {seq} {name}: {len(poses)} poses, truth has {len(truth)}")
        data[seq] = {
            "scans": len(truth),
            "scansPerStretch": per,
            "paths": {"truth": path(truth), **{name: path(p) for name, p in runs.items()}},
            "stretchErrorCm": {"atlas": stretch_errors(truth, runs["atlas"], per),
                               "kiss": stretch_errors(truth, runs["kiss"], per)},
        }
    with open(out, "w") as f:
        f.write("// Generated by tools/export_web_results.py from recorded runs (see docs/kitti.md).\n"
                "// Do not edit by hand. Paths: meters, [u, v] = [-y, x] in scan 0's Velodyne frame,\n"
                f"// every {STEP}rd pose. Errors: mean step error in cm per stretch of scans.\n"
                "import type { KittiRecording } from \"../lib/kittiPlot\";\n\n"
                "export const KITTI_RECORDINGS: Record<\"07\" | \"04\", KittiRecording> = ")
        f.write(json.dumps(data, separators=(",", ":")))
        f.write(";\n")
    for seq in data:
        print(seq, data[seq]["scans"], "scans;", {k: len(v) for k, v in data[seq]["paths"].items()},
              "atlas", data[seq]["stretchErrorCm"]["atlas"], "kiss", data[seq]["stretchErrorCm"]["kiss"])


if __name__ == "__main__":
    main()
